public class Algoritmo16 {
    public static void main(String[] args) {

        // Mostre números pares de 0 a 200 usando while

        int i = 1;

        while (i <= 200) {

            if (i % 2 == 0) {
                System.out.println(i);
                i++;
            } else {
                i++;
            }

        }
    }
}
